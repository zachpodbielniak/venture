#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-or-later
#
# venture-tallow-bindings.sh - expose the compiled kernels to .tlw plugins.
#
# A .tlw plugin runs on the suet VM, but the kernel math it calls must be
# the compiled code the server itself runs, never an interpreted copy. This
# reads the scalar signatures of src/kernels/vk_*.tlw and writes:
#
#   OUT.tlw  module `venture_kernels`: the kernels' units and one
#            `pure extern fn <module>_<fn>` per scalar kernel, bound to a
#            host symbol (embedded into the server as a host module)
#   OUT.c    one TallowSuetHostFunc per kernel that unpacks the VM's
#            GValues, calls vk_<module>_<fn> with a contract-violation
#            guard installed, and packs the result; plus
#            venture_tallow_kernels_install(), which registers them and the
#            module source on a TallowSuet
#
# A kernel is exported when the line above its signature is `/* @export */`
# (an author's choice of what plugins see, so helpers stay private without
# hiding them from `tallow verify` the way @internal would), its signature
# starts on one line, its parameters are all i64 (any unit) or bool and its
# result is i64, bool or ?i64 (any unit). Kernels taking enums, arrays,
# strings or sum types stay C-only; plugins reach that behaviour through
# VENTURE's own API.
set -euo pipefail
export LC_ALL=C

usage () {
	cat <<'HELP'
Usage: venture-tallow-bindings.sh OUT_TLW OUT_C KERNEL.tlw...
       venture-tallow-bindings.sh --help | --license
Generate the VM bindings of the compiled Tallow kernels.
Example: tools/venture-tallow-bindings.sh build/debug/gen/kernels/vk-host.tlw \
         build/debug/gen/kernels/vk-host.c src/kernels/vk_*.tlw
HELP
}

case ${1:-} in
	-h|--help) usage; exit 0 ;;
	--license) echo 'SPDX-License-Identifier: AGPL-3.0-or-later'; exit 0 ;;
esac
[[ $# -ge 3 ]] || { usage >&2; exit 1; }

out_tlw="${1}"
out_c="${2}"
shift 2

# strip a module qualifier from units: `i64<U.minor>` -> `i64<minor>`
strip_units () {
	sed -E 's/<([A-Za-z_][A-Za-z0-9_]*)\./</g'
}

# --- collect the units and the exportable signatures -----------------------

units=""
sigs=""
for f in "$@"; do
	mod=$(basename "${f}" .tlw)
	mod=${mod#vk_}
	units+=$(grep -E '^unit [a-z_]+( = [0-9]+ \* [a-z_]+)?;' "${f}" || true)
	units+=$'\n'
	# `pure fn name(params) -> ret ...` right under a `/* @export */` line;
	# the return type is the first token after `->` (awk takes it)
	while IFS= read -r line; do
		sigs+="${mod}|${line}"$'\n'
	done < <(awk 'prev ~ /^\/\* @export \*\/$/ && /^pure fn [a-z_][a-z0-9_]*\(/ { print } { prev = $0 }' "${f}" \
		| strip_units || true)
done

# --- write both outputs from one awk pass ----------------------------------

tmp_tlw="${out_tlw}.tmp"
tmp_c="${out_c}.tmp"

{
	echo "/* Generated by tools/venture-tallow-bindings.sh - do not edit. */"
	echo "/*"
	echo " * The compiled kernels, callable from a .tlw plugin. Each function runs"
	echo " * the same machine code as the server; it is not interpreted. A violated"
	echo " * requires ends the plugin's call with an error naming the clause."
	echo " */"
	echo "module venture_kernels;"
	echo
	printf '%s\n' "${units}" | grep -v '^$' | sort -u
	echo
} > "${tmp_tlw}"

printf '%s' "${sigs}" | awk -v tlw="${tmp_tlw}" -v cfile="${tmp_c}" '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function base(t) { t = trim(t); sub(/<.*/, "", t); return t }
BEGIN {
	n = 0
	print "/* Generated by tools/venture-tallow-bindings.sh - do not edit. */" > cfile
	print "" > cfile
	print "#include <setjmp.h>" > cfile
	print "#include <tallow-suet.h>" > cfile
	print "#include <vk-kernels.h>" > cfile
	print "#include \"plugin/venture-tallow-runtime-private.h\"" > cfile
	print "" > cfile
}
{
	split($0, parts, "|")
	mod = parts[1]
	sig = parts[2]
	# name
	name = sig
	sub(/^pure fn /, "", name)
	sub(/\(.*/, "", name)
	# params between the first ( and the matching )
	params = sig
	sub(/^[^(]*\(/, "", params)
	ret = params
	sub(/\).*$/, "", params)
	if (ret !~ /\) -> /)
		next
	sub(/^.*\) -> /, "", ret)
	ret = trim(ret)
	sub(/[ \t].*$/, "", ret)
	rbase = ret
	optional = 0
	if (rbase ~ /^\?/) { optional = 1; rbase = substr(rbase, 2) }
	rbase = base(rbase)
	if (rbase != "i64" && rbase != "bool")
		next
	if (optional && rbase != "i64")
		next
	np = 0
	ok = 1
	if (trim(params) != "") {
		np = split(params, plist, ",")
		for (i = 1; i <= np; i++) {
			p = trim(plist[i])
			pname[i] = p; sub(/:.*/, "", pname[i]); pname[i] = trim(pname[i])
			ptype[i] = p; sub(/^[^:]*:/, "", ptype[i]); ptype[i] = trim(ptype[i])
			pb[i] = base(ptype[i])
			if (pb[i] != "i64" && pb[i] != "bool")
				ok = 0
		}
	}
	if (!ok)
		next

	host = mod "_" name
	sym = "venture_tlw_vk_" host
	print "pure extern fn " host "(" trim(params) ") -> " ret " = \"" sym "\";" >> tlw

	# the C trampoline
	print "static gboolean" > cfile
	print sym "(" > cfile
	print "\tTallowSuet\t*vm," > cfile
	print "\tconst GValue\t*args," > cfile
	print "\tguint\t\t n_args," > cfile
	print "\tGValue\t\t*result," > cfile
	print "\tgpointer\t user_data," > cfile
	print "\tGError\t\t**error" > cfile
	print "){" > cfile
	print "\tVentureTallowGuard guard;" > cfile
	if (optional) print "\tvolatile TlwOptI64 r;" > cfile
	else if (rbase == "bool") print "\tvolatile gboolean r;" > cfile
	else print "\tvolatile gint64 r;" > cfile
	print "" > cfile
	print "\t(void)vm;" > cfile
	print "\t(void)user_data;" > cfile
	print "\tif (n_args != " np ")" > cfile
	print "\t\treturn venture_tallow_kernel_arity(\"" host "\", " np ", n_args, error);" > cfile
	call = "vk_" mod "_" name "("
	for (i = 1; i <= np; i++) {
		if (pb[i] == "bool")
			call = call "g_value_get_boolean(&args[" i - 1 "])"
		else
			call = call "g_value_get_int64(&args[" i - 1 "])"
		if (i < np) call = call ", "
	}
	call = call ")"
	if (optional) print "\tr.has = FALSE;" > cfile
	else print "\tr = 0;" > cfile
	print "\tVENTURE_TALLOW_GUARDED(guard, r = " call ");" > cfile
	print "\tif (NULL != guard.violation)" > cfile
	print "\t\treturn venture_tallow_kernel_violation(&guard, \"" host "\", error);" > cfile
	if (optional) {
		print "\tif (r.has) {" > cfile
		print "\t\tg_value_init(result, G_TYPE_INT64);" > cfile
		print "\t\tg_value_set_int64(result, r.val);" > cfile
		print "\t}" > cfile
	} else if (rbase == "bool") {
		print "\tg_value_init(result, G_TYPE_BOOLEAN);" > cfile
		print "\tg_value_set_boolean(result, r);" > cfile
	} else {
		print "\tg_value_init(result, G_TYPE_INT64);" > cfile
		print "\tg_value_set_int64(result, r);" > cfile
	}
	print "\treturn TRUE;" > cfile
	print "}" > cfile
	print "" > cfile
	syms[n] = sym
	n++
}
END {
	print "static const VentureTallowHostEntry venture_tallow_kernel_table[] = {" > cfile
	for (i = 0; i < n; i++)
		print "\t{ \"" syms[i] "\", " syms[i] " }," > cfile
	print "\t{ NULL, NULL }" > cfile
	print "};" > cfile
	print "" > cfile
	print "const VentureTallowHostEntry *" > cfile
	print "venture_tallow_kernel_functions(void)" > cfile
	print "{" > cfile
	print "\treturn venture_tallow_kernel_table;" > cfile
	print "}" > cfile
}
'

# the module source, embedded as one C string
{
	echo
	echo "const gchar *"
	echo "venture_tallow_kernel_module_source(void)"
	echo "{"
	echo "	return"
	sed 's/\\/\\\\/g; s/"/\\"/g; s/^/\t\t"/; s/$/\\n"/' "${tmp_tlw}"
	echo "	;"
	echo "}"
} >> "${tmp_c}"

mv "${tmp_tlw}" "${out_tlw}"
mv "${tmp_c}" "${out_c}"
